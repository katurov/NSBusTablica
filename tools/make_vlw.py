#!/usr/bin/env python3
"""Make anti-aliased TFT_eSPI smooth fonts (.vlw as a C array) for the T-Display header.

Only the glyphs the board needs: printable ASCII + Serbian Latin (Č č Ć ć Š š Ž ž Đ đ) + '…'. Built from Roboto
Condensed (Apache 2.0 / OFL, variable font, instance chosen by name) so long Novi Sad stop names fit in two lines.

  python3 tools/make_vlw.py <font.ttf> <variation-name> <out.h> NAME:SIZE [NAME:SIZE ...]
  e.g. python3 tools/make_vlw.py RobotoCondensed-VariableFont_wght.ttf SemiBold firmware/include/hdr_font.h hdr24:24

VLW layout (big-endian int32, as read by TFT_eSPI Smooth_font.cpp loadMetrics):
  header  glyph count, version (11), font size, 0, ascent, descent
  glyph   unicode, height, width, xAdvance, dY (top above baseline), dX (left offset), 0
  then the 8-bit alpha bitmaps, width*height bytes each, same order. Space is not stored (TFT_eSPI handles it).
Built with Grok Bot.
"""
import struct, sys
from PIL import Image, ImageDraw, ImageFont

CHARS = [chr(c) for c in range(0x21, 0x7F)] + list("ČčĆćŠšŽžĐđ…")


def glyphs(ttf, var, size):
    f = ImageFont.truetype(ttf, size)
    if var:
        f.set_variation_by_name(var)
    asc, desc = f.getmetrics()
    out = []
    for ch in CHARS:
        x0, y0, x1, y1 = f.getbbox(ch, anchor="ls")
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        img = Image.new("L", (max(1, w), max(1, h)), 0)
        if w and h:
            ImageDraw.Draw(img).text((-x0, -y0), ch, font=f, fill=255, anchor="ls")
        out.append({"u": ord(ch), "w": w, "h": h, "adv": int(round(f.getlength(ch))), "dy": -y0, "dx": x0,
                    "bm": img.tobytes() if w and h else b""})
    return asc, desc, out


def vlw(ttf, var, size):
    asc, desc, gl = glyphs(ttf, var, size)
    b = struct.pack(">6i", len(gl), 11, size, 0, asc, desc)
    for g in gl:
        b += struct.pack(">7i", g["u"], g["h"], g["w"], g["adv"], g["dy"], g["dx"], 0)
    for g in gl:
        b += g["bm"]
    return b


def main():
    ttf, var, out = sys.argv[1:4]
    parts = ["// Generated by tools/make_vlw.py from %s (%s). Do not edit." % (ttf.split("/")[-1], var),
             "#pragma once", "#include <stdint.h>", "#include <pgmspace.h>", ""]
    for spec in sys.argv[4:]:
        name, size = spec.split(":")
        data = vlw(ttf, var, int(size))
        parts.append("// %s px, %d bytes" % (size, len(data)))
        parts.append("const uint8_t %s[] PROGMEM = {" % name)
        for i in range(0, len(data), 24):
            parts.append("  " + ",".join("0x%02x" % c for c in data[i:i + 24]) + ",")
        parts.append("};\n")
    open(out, "w").write("\n".join(parts))


if __name__ == "__main__":
    main()
